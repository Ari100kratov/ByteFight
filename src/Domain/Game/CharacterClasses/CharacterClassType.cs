namespace Domain.Game.CharacterClasses;

/// <summary>
/// Класс персонажа. Классы со значением 10 и выше — действующая
/// древнеславянская линейка; ранние значения оставлены для совместимости.
/// </summary>
public enum CharacterClassType
{
    /// <summary>Устаревший класс «Воин».</summary>
    Warrior = 1,

    /// <summary>Устаревший класс «Маг».</summary>
    Mage = 2,

    /// <summary>
    /// Витязь — ратник ближнего боя: меч, щит и богатырская стойкость.
    /// </summary>
    Vityaz = 10,

    /// <summary>
    /// Волхв — повелитель стихий: грозы, мороза и света.
    /// </summary>
    Volkhv = 11,

    /// <summary>
    /// Охотник — ловчий чащоб: лук, силки и отравленные стрелы.
    /// </summary>
    Okhotnik = 12,

    /// <summary>
    /// Ведунья — травница и шептунья: лечение, порча и духи-обереги.
    /// </summary>
    Vedunya = 13
}
